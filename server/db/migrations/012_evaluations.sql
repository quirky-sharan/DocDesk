-- 012 Evaluations: the scoreboard, kept in the database.
--
-- Phase 4 wrote a benchmark, said "run it once a key is in and record the real
-- numbers here", and the numbers were never written down. Giving results a home
-- is what stops that happening twice: `npm run bench:receptionist` writes here,
-- the AI page reads it, and a model's score is a fact about the system rather
-- than something in somebody's terminal scrollback.
--
-- The protocol this table exists to support: a model does not enter the routing
-- pool until it has passed. A must-refuse case that gets a helpful answer is a
-- hard fail and blocks the model, which is why must_pass is a column and not a
-- convention.

CREATE TABLE IF NOT EXISTS eval_cases (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        text NOT NULL,
  suite       text NOT NULL,
  input       text NOT NULL,
  expectation jsonb NOT NULL DEFAULT '{}'::jsonb,
  must_pass   boolean NOT NULL DEFAULT false,
  degraded    boolean NOT NULL DEFAULT false,
  notes       text,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT eval_cases_suite_check CHECK (suite IN (
    'intent', 'slots', 'datetime', 'booking', 'must_refuse', 'must_escalate',
    'must_not_answer', 'injection', 'latency', 'conversation'
  )),
  CONSTRAINT eval_cases_slug_format CHECK (slug ~ '^[a-z0-9][a-z0-9_-]{0,79}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS eval_cases_slug_key ON eval_cases (slug);
CREATE INDEX IF NOT EXISTS eval_cases_suite_idx ON eval_cases (suite, is_active);
COMMENT ON TABLE eval_cases IS 'The cases every pooled model is scored against.';
COMMENT ON COLUMN eval_cases.must_pass IS 'A failure here blocks the model from the routing pool outright. Refusals and escalations are must_pass; a slightly wrong phrasing is not.';
COMMENT ON COLUMN eval_cases.degraded IS 'Part of the subset that must still pass with no API keys at all.';

CREATE TABLE IF NOT EXISTS eval_runs (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_key  text,
  model         text,
  mode          text NOT NULL DEFAULT 'normal',
  started_at    timestamptz NOT NULL DEFAULT now(),
  finished_at   timestamptz,
  total         integer NOT NULL DEFAULT 0,
  passed        integer NOT NULL DEFAULT 0,
  failed        integer NOT NULL DEFAULT 0,
  blocked       boolean NOT NULL DEFAULT false,
  p50_ms        integer,
  p95_ms        integer,
  notes         text,
  CONSTRAINT eval_runs_mode_check CHECK (mode IN ('normal', 'degraded')),
  CONSTRAINT eval_runs_counts_check CHECK (passed >= 0 AND failed >= 0 AND total >= 0)
);
CREATE INDEX IF NOT EXISTS eval_runs_model_idx ON eval_runs (model, started_at DESC);
COMMENT ON TABLE eval_runs IS 'One execution of the suite against one model.';
COMMENT ON COLUMN eval_runs.blocked IS 'True when a must_pass case failed. The model is kept out of the routing pool while this is the latest run for it.';

CREATE TABLE IF NOT EXISTS eval_results (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id     bigint NOT NULL REFERENCES eval_runs (id) ON DELETE CASCADE,
  case_id    bigint REFERENCES eval_cases (id) ON DELETE SET NULL,
  slug       text NOT NULL,
  suite      text NOT NULL,
  passed     boolean NOT NULL,
  latency_ms integer,
  actual     text,
  detail     jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS eval_results_run_idx ON eval_results (run_id, passed);
COMMENT ON TABLE eval_results IS 'Per-case outcomes, keeping the raw output. Read this before touching a prompt: Phase 5''s shape fix only happened because someone looked at the raw JSON instead of guessing.';

-- The scoreboard: the latest run per model, best first.
CREATE OR REPLACE VIEW v_eval_scoreboard AS
SELECT DISTINCT ON (r.provider_key, r.model, r.mode)
  r.id AS run_id,
  r.provider_key,
  r.model,
  r.mode,
  r.started_at,
  r.total,
  r.passed,
  r.failed,
  r.blocked,
  r.p50_ms,
  r.p95_ms,
  CASE WHEN r.total > 0 THEN round(r.passed::numeric * 100 / r.total, 1) ELSE NULL END AS percent
FROM eval_runs r
WHERE r.finished_at IS NOT NULL
ORDER BY r.provider_key, r.model, r.mode, r.started_at DESC;
COMMENT ON VIEW v_eval_scoreboard IS 'The most recent finished run for each model, which is what decides whether it is allowed in the pool.';
