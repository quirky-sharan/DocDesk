-- 011 AI operations: which models exist, what they cost us, and what is left.
--
-- Phase 5 lost an afternoon to Groq retiring llama-3.3-70b-versatile out from
-- under a hardcoded name. Checking again while writing this phase, both
-- OpenRouter models still hardcoded in lib/llm are gone from its free list too.
-- So nothing here stores a model name as configuration: models are DISCOVERED
-- from each provider and written into ai_models, and the code matches them
-- against a preference expression instead of naming them.
--
-- ai_budget_windows is persisted rather than kept in memory for one specific
-- reason: a restart must not hand the process a fresh daily allowance it does
-- not actually have. An in-memory counter resets when nodemon reloads; the
-- provider's does not.

CREATE TABLE IF NOT EXISTS ai_providers (
  key           text PRIMARY KEY,
  label         text NOT NULL,
  base_url      text NOT NULL,
  auth_style    text NOT NULL DEFAULT 'bearer',
  key_var       text,
  console_url   text,
  is_enabled    boolean NOT NULL DEFAULT true,
  status        text NOT NULL DEFAULT 'unknown',
  status_reason text,
  status_until  timestamptz,
  latency_ms    integer,
  health        numeric(4, 3) NOT NULL DEFAULT 1,
  checked_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ai_providers_key_format CHECK (key ~ '^[a-z][a-z0-9_-]{0,39}$'),
  CONSTRAINT ai_providers_auth_check CHECK (auth_style IN ('bearer', 'query', 'header', 'none')),
  CONSTRAINT ai_providers_status_check CHECK (status IN (
    'unknown', 'ready', 'busy', 'quota_daily', 'credits_exhausted', 'auth', 'down', 'not_configured', 'disabled'
  )),
  CONSTRAINT ai_providers_health_check CHECK (health BETWEEN 0 AND 1)
);
COMMENT ON TABLE ai_providers IS 'Where models come from. The API key itself is never stored here - it lives in server/.env and only its variable name is recorded.';
COMMENT ON COLUMN ai_providers.status IS 'quota_daily and credits_exhausted are different states with different sentences. Confusing the two is the most annoying bug this class of system has.';
COMMENT ON COLUMN ai_providers.status_until IS 'When this state is expected to lift - the reset time for a daily cap, or when a cooling-off ends.';

CREATE TABLE IF NOT EXISTS ai_models (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_key     text NOT NULL REFERENCES ai_providers (key) ON DELETE CASCADE,
  model            text NOT NULL,
  family           text,
  tier             text,
  context_window   integer,
  capabilities     jsonb NOT NULL DEFAULT '[]'::jsonb,
  tokenizer_factor numeric(5, 3) NOT NULL DEFAULT 1,
  is_enabled       boolean NOT NULL DEFAULT true,
  discovered_at    timestamptz NOT NULL DEFAULT now(),
  last_seen_at     timestamptz NOT NULL DEFAULT now(),
  last_error       text,
  last_error_at    timestamptz,
  bench_score      numeric(5, 2),
  bench_run_at     timestamptz,
  CONSTRAINT ai_models_tier_check CHECK (tier IS NULL OR tier IN ('nano', 'small', 'mid')),
  CONSTRAINT ai_models_tokenizer_check CHECK (tokenizer_factor BETWEEN 0.1 AND 10)
);
CREATE UNIQUE INDEX IF NOT EXISTS ai_models_key ON ai_models (provider_key, model);
CREATE INDEX IF NOT EXISTS ai_models_tier_idx ON ai_models (tier, is_enabled);
COMMENT ON TABLE ai_models IS 'Every model each provider says this key can use, refreshed by discovery. Nothing here is configuration - it is a record of what was found.';
COMMENT ON COLUMN ai_models.tokenizer_factor IS 'Measured, not assumed: qwen counted the same prompt at about twice what gpt-oss did, which throws every budget estimate out if taken as 1.';
COMMENT ON COLUMN ai_models.bench_score IS 'Null means it has not passed the evaluation suite, and it does not enter the routing pool until it has.';

CREATE TABLE IF NOT EXISTS ai_budget_windows (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_key     text NOT NULL REFERENCES ai_providers (key) ON DELETE CASCADE,
  model            text NOT NULL,
  window_kind      text NOT NULL,
  limit_value      bigint NOT NULL,
  consumed         bigint NOT NULL DEFAULT 0,
  refill_mode      text NOT NULL DEFAULT 'continuous',
  window_started_at timestamptz NOT NULL DEFAULT now(),
  reset_at         timestamptz,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ai_budget_kind_check CHECK (window_kind IN ('rpm', 'rpd', 'tpm', 'tpd')),
  CONSTRAINT ai_budget_refill_check CHECK (refill_mode IN ('continuous', 'fixed')),
  CONSTRAINT ai_budget_limit_check CHECK (limit_value > 0),
  CONSTRAINT ai_budget_consumed_check CHECK (consumed >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ai_budget_windows_key ON ai_budget_windows (provider_key, model, window_kind);
COMMENT ON TABLE ai_budget_windows IS 'What is left of each free allowance, kept across restarts so a reload cannot invent headroom that does not exist.';
COMMENT ON COLUMN ai_budget_windows.refill_mode IS 'continuous = a token bucket that refills every second (Groq per-minute limits work this way); fixed = the whole allowance returns at reset_at. Treating a continuous bucket as fixed makes the system give up far too early.';

CREATE TABLE IF NOT EXISTS ai_usage (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint REFERENCES conversations (id) ON DELETE SET NULL,
  purpose         text NOT NULL DEFAULT 'chat',
  provider_key    text,
  model           text,
  tier            text,
  tokens_in       integer NOT NULL DEFAULT 0,
  tokens_out      integer NOT NULL DEFAULT 0,
  latency_ms      integer,
  outcome         text NOT NULL DEFAULT 'ok',
  error_class     text,
  retried_from    text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ai_usage_outcome_check CHECK (outcome IN ('ok', 'error', 'cached', 'skipped')),
  CONSTRAINT ai_usage_error_class_check CHECK (error_class IS NULL OR error_class IN (
    'transient', 'rate_limited', 'quota_daily', 'credits_exhausted', 'auth',
    'model_missing', 'context_overflow', 'content_filter', 'bad_request'
  ))
);
CREATE INDEX IF NOT EXISTS ai_usage_created_idx ON ai_usage (created_at DESC);
CREATE INDEX IF NOT EXISTS ai_usage_model_idx ON ai_usage (provider_key, model, created_at DESC);
COMMENT ON TABLE ai_usage IS 'One row per model call: the cost ledger, in tokens, and the trail for working out why something was slow or wrong.';
COMMENT ON COLUMN ai_usage.error_class IS 'The taxonomy the whole fallback chain turns on. Every provider''s error body maps to exactly one of these.';

CREATE TABLE IF NOT EXISTS ai_cache (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question     text NOT NULL,
  normalised   text NOT NULL,
  embedding    real[],
  answer       text NOT NULL,
  model        text,
  hit_count    integer NOT NULL DEFAULT 0,
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_hit_at  timestamptz,
  expires_at   timestamptz,
  CONSTRAINT ai_cache_hit_count_check CHECK (hit_count >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ai_cache_normalised_key ON ai_cache (normalised);
CREATE INDEX IF NOT EXISTS ai_cache_expiry_idx ON ai_cache (expires_at) WHERE expires_at IS NOT NULL;
COMMENT ON TABLE ai_cache IS 'Answers to questions already asked. "What time do you close" does not need a model twice.';

CREATE TABLE IF NOT EXISTS ai_events (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         text NOT NULL,
  provider_key text,
  model        text,
  message      text NOT NULL,
  detail       jsonb NOT NULL DEFAULT '{}'::jsonb,
  seen         boolean NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ai_events_kind_check CHECK (kind IN (
    'discovered', 'model_retired', 'quota_daily', 'credits_exhausted', 'auth_failed',
    'provider_down', 'fell_back', 'recovered', 'budget_capped', 'bench_failed', 'pinned'
  ))
);
CREATE INDEX IF NOT EXISTS ai_events_created_idx ON ai_events (created_at DESC);
CREATE INDEX IF NOT EXISTS ai_events_unseen_idx ON ai_events (created_at DESC) WHERE NOT seen;
COMMENT ON TABLE ai_events IS 'Things worth telling the owner in plain English: a provider went down, a model was retired, the free allowance ran out and what happened instead.';
COMMENT ON COLUMN ai_events.message IS 'Written as a sentence a non-technical person can act on, not as a log line.';

CREATE OR REPLACE TRIGGER ai_providers_touch BEFORE UPDATE ON ai_providers FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Usage per model per day, for the chart on the AI page.
CREATE OR REPLACE FUNCTION ai_usage_by_day(p_from date, p_to date, p_tz text)
RETURNS TABLE (day date, provider_key text, model text, calls bigint, tokens_in bigint, tokens_out bigint, errors bigint, p50_ms integer)
LANGUAGE sql STABLE AS $$
  SELECT (u.created_at AT TIME ZONE p_tz)::date AS day,
         u.provider_key,
         u.model,
         count(*),
         COALESCE(sum(u.tokens_in), 0),
         COALESCE(sum(u.tokens_out), 0),
         count(*) FILTER (WHERE u.outcome = 'error'),
         percentile_disc(0.5) WITHIN GROUP (ORDER BY u.latency_ms)::integer
    FROM ai_usage u
   WHERE u.created_at >= (p_from::timestamp AT TIME ZONE p_tz)
     AND u.created_at < ((p_to + 1)::timestamp AT TIME ZONE p_tz)
   GROUP BY 1, 2, 3
   ORDER BY 1, 2, 3
$$;
COMMENT ON FUNCTION ai_usage_by_day(date, date, text) IS 'Calls, tokens, errors and median latency per model per day, in the business timezone.';
