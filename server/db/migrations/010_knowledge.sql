-- 010 Knowledge: what the receptionist is allowed to say about the business.
--
-- The rule this table exists to enforce: the receptionist does not answer a
-- factual question about the business unless retrieval found something that
-- supports the answer. Making up opening hours is the failure that gets a real
-- business in trouble, and no amount of prompt wording prevents it reliably.
-- The gate is in lib/knowledge/, and this is what it searches.
--
-- On embeddings. pgvector is NOT available in PGlite (checked against 0.5.8,
-- which is the latest - there is no vector export and no separate package), so
-- an embedding is stored as a plain real[] that works on every engine. A small
-- shop's knowledge base is tens to hundreds of chunks, where a cosine loop in
-- SQL is perfectly fast and an index would not earn its keep. A hosted
-- PostgreSQL with pgvector can add an index later without changing any of this.
--
-- Retrieval is hybrid on purpose. Lexical search often beats embeddings on
-- short queries over a small corpus, which is exactly this case, and fusing the
-- two rankings is strictly better than choosing one. If no embedding is
-- available at all - no model, no key, offline - kb_search still works from the
-- lexical half alone. Retrieval degrades; it never stops.

CREATE TABLE IF NOT EXISTS kb_documents (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        text NOT NULL,
  body         text NOT NULL DEFAULT '',
  source       text NOT NULL DEFAULT 'manual',
  is_generated boolean NOT NULL DEFAULT false,
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  row_version  integer NOT NULL DEFAULT 1,
  CONSTRAINT kb_documents_title_length CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  CONSTRAINT kb_documents_source_check CHECK (source IN ('manual', 'settings', 'services', 'products', 'hours', 'faq'))
);
CREATE UNIQUE INDEX IF NOT EXISTS kb_documents_generated_key ON kb_documents (source, lower(btrim(title))) WHERE is_generated;
COMMENT ON TABLE kb_documents IS 'What the receptionist may tell people. Some rows are written by hand; generated ones are rebuilt from live data whenever it changes.';
COMMENT ON COLUMN kb_documents.is_generated IS 'True means this is derived from settings, services or hours and will be overwritten. Edit the underlying data instead.';

CREATE TABLE IF NOT EXISTS kb_chunks (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL REFERENCES kb_documents (id) ON DELETE CASCADE,
  ordinal     integer NOT NULL DEFAULT 0,
  content     text NOT NULL,
  embedding   real[],
  embedded_by text,
  tsv         tsvector GENERATED ALWAYS AS (to_tsvector('english', content)) STORED,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT kb_chunks_content_length CHECK (length(btrim(content)) BETWEEN 1 AND 8000)
);
CREATE INDEX IF NOT EXISTS kb_chunks_document_idx ON kb_chunks (document_id, ordinal);
CREATE INDEX IF NOT EXISTS kb_chunks_tsv_idx ON kb_chunks USING gin (tsv);
COMMENT ON TABLE kb_chunks IS 'Knowledge split into retrievable pieces, each with a full-text vector and optionally an embedding.';
COMMENT ON COLUMN kb_chunks.embedding IS 'A plain real[] rather than pgvector, which the embedded engine does not have. Null is normal and only weakens ranking.';
COMMENT ON COLUMN kb_chunks.embedded_by IS 'Which model produced the embedding, so a change of model can invalidate the old ones.';

DO $$
BEGIN
  CREATE INDEX IF NOT EXISTS kb_chunks_trgm_idx ON kb_chunks USING gin (content gin_trgm_ops);
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'Trigram index on kb_chunks skipped (%).', SQLERRM;
END
$$;

CREATE TABLE IF NOT EXISTS kb_feedback (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chunk_id        bigint REFERENCES kb_chunks (id) ON DELETE SET NULL,
  conversation_id bigint REFERENCES conversations (id) ON DELETE SET NULL,
  question        text NOT NULL,
  answered        boolean NOT NULL DEFAULT true,
  score           numeric(6, 4),
  corrected       boolean NOT NULL DEFAULT false,
  correction      text,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS kb_feedback_unanswered_idx ON kb_feedback (created_at DESC) WHERE NOT answered;
COMMENT ON TABLE kb_feedback IS 'Which chunk answered which question, and whether the operator later corrected it. Rows with answered = false are the knowledge gaps worth filling.';

-- Cosine similarity between two embeddings held as plain arrays.
-- Returns 0 rather than raising when either side is missing or the two were
-- produced by different models and do not line up - a ranking signal that is
-- unavailable should quietly count for nothing, not break the query.
CREATE OR REPLACE FUNCTION cosine_similarity(a real[], b real[])
RETURNS double precision
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN a IS NULL OR b IS NULL THEN 0
    WHEN array_length(a, 1) IS DISTINCT FROM array_length(b, 1) THEN 0
    ELSE (
      SELECT CASE WHEN norm = 0 THEN 0 ELSE dot / norm END
        FROM (
          SELECT sum(x::double precision * y::double precision) AS dot,
                 sqrt(sum(x::double precision * x::double precision)) * sqrt(sum(y::double precision * y::double precision)) AS norm
            FROM unnest(a, b) AS t(x, y)
        ) s
    )
  END
$$;
COMMENT ON FUNCTION cosine_similarity(real[], real[]) IS 'Cosine similarity for embeddings stored as arrays. Zero when either is missing or the lengths differ.';

-- Hybrid retrieval: full text and trigram on one side, embedding on the other,
-- combined by reciprocal rank fusion. RRF needs only the ORDER of each ranking,
-- not its scores, which is why it can fuse a ts_rank with a cosine without
-- anybody having to normalise one against the other.
--
-- p_min_lexical matters more than it looks. pg_trgm's similarity() returns a
-- small non-zero score for almost any pair of strings, so without a floor every
-- query "finds" something and the answerability gate would think it had support
-- for an answer it does not have. Asking about parking when the knowledge base
-- only covers opening hours must come back empty, not weakly ranked. The gate
-- in lib/knowledge applies its own threshold on top; this one just keeps
-- obvious noise out of the result.
CREATE OR REPLACE FUNCTION kb_search(
  p_query       text,
  p_embedding   real[] DEFAULT NULL,
  p_limit       integer DEFAULT 5,
  p_min_lexical double precision DEFAULT 0.05
)
RETURNS TABLE (
  chunk_id    bigint,
  document_id bigint,
  title       text,
  content     text,
  score       double precision,
  lexical     double precision,
  semantic    double precision
)
LANGUAGE sql STABLE AS $$
  WITH scored AS (
    SELECT
      k.id,
      k.document_id,
      d.title,
      k.content,
      GREATEST(
        ts_rank(k.tsv, plainto_tsquery('english', p_query)),
        similarity(k.content, p_query)
      )::double precision AS lexical,
      cosine_similarity(k.embedding, p_embedding) AS semantic
    FROM kb_chunks k
    JOIN kb_documents d ON d.id = k.document_id
    WHERE d.is_active
  ),
  ranked AS (
    SELECT *,
      rank() OVER (ORDER BY lexical DESC)  AS lexical_rank,
      rank() OVER (ORDER BY semantic DESC) AS semantic_rank
    FROM scored
    WHERE lexical >= COALESCE(p_min_lexical, 0.05)
       OR semantic >= 0.35
  )
  SELECT
    r.id,
    r.document_id,
    r.title,
    r.content,
    -- 60 is the constant from the original RRF paper; it stops the top rank
    -- from dominating so completely that the other ranking never matters.
    (1.0 / (60 + r.lexical_rank)
      + CASE WHEN p_embedding IS NULL THEN 0 ELSE 1.0 / (60 + r.semantic_rank) END)::double precision AS score,
    r.lexical,
    r.semantic
  FROM ranked r
  ORDER BY score DESC, r.lexical DESC, r.id
  LIMIT GREATEST(COALESCE(p_limit, 5), 1)
$$;
COMMENT ON FUNCTION kb_search(text, real[], integer, double precision) IS 'Hybrid knowledge search: full text and trigram fused with embedding similarity by reciprocal rank fusion. Works with no embedding at all, just less well.';

CREATE OR REPLACE TRIGGER kb_documents_touch BEFORE UPDATE ON kb_documents FOR EACH ROW EXECUTE FUNCTION touch_row('versioned');
CREATE OR REPLACE TRIGGER kb_documents_audit AFTER INSERT OR UPDATE OR DELETE ON kb_documents FOR EACH ROW EXECUTE FUNCTION audit_row();

CREATE OR REPLACE FUNCTION knowledge_capabilities() RETURNS jsonb
LANGUAGE sql STABLE AS $$
  SELECT jsonb_build_object(
    'pgvector', EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'vector'),
    'trigram', EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm'),
    'full_text', true,
    'chunks', (SELECT count(*) FROM kb_chunks),
    'embedded', (SELECT count(*) FROM kb_chunks WHERE embedding IS NOT NULL)
  )
$$;
COMMENT ON FUNCTION knowledge_capabilities() IS 'What retrieval this database can actually do, for the Health tab. pgvector is absent on the embedded engine and that is expected.';
