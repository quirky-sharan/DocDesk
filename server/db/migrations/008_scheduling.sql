-- Two bookings for one resource cannot overlap. tstzrange is half-open, so an
-- appointment ending at 11:00 and one starting at 11:00 are not an overlap -
-- back-to-back is exactly what a busy day looks like. Cancelled and no-show
-- appointments are excluded so a cancelled slot frees up immediately.
--
-- Added separately from CREATE TABLE on purpose: if btree_gist is missing the
-- table must still exist, with book_appointment()'s lock as the guard.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_no_overlap') THEN
    ALTER TABLE appointments ADD CONSTRAINT appointments_no_overlap
      EXCLUDE USING gist (
        resource_id WITH =,
        tstzrange(starts_at, ends_at) WITH &&
      ) WHERE (status NOT IN ('cancelled', 'no_show'));
  END IF;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'Could not add appointments_no_overlap (%). book_appointment() still serialises on the resource.', SQLERRM;
END
$$;

