-- Availability, computed in SQL --------------------------------------------------
-- Every candidate slot is generated from the opening hours, minus closures,
-- minus what is already booked, minus each service's buffers, bucketed in the
-- business timezone. Doing this in SQL rather than filtering rows in JS is
-- deliberate: filtering after the fact is how the stock counts went wrong in
-- Phase 2, and a slot list that is subtly wrong books real people into a room
-- that is already occupied.
CREATE OR REPLACE FUNCTION available_slots(
  p_service_id   bigint,
  p_resource_id  bigint,
  p_from         timestamptz,
  p_to           timestamptz,
  p_step_minutes integer DEFAULT NULL
)
RETURNS TABLE (resource_id bigint, starts_at timestamptz, ends_at timestamptz)
LANGUAGE sql STABLE AS $$
  WITH zone AS (
    SELECT business_timezone() AS tz
  ),
  svc AS (
    SELECT s.duration_minutes, s.buffer_before_minutes, s.buffer_after_minutes, s.max_per_day
      FROM services s
     WHERE s.id = p_service_id AND s.is_active
  ),
  usable AS (
    SELECT r.id
      FROM resources r
      JOIN resource_services rs ON rs.resource_id = r.id AND rs.service_id = p_service_id
     WHERE r.is_active
       AND (p_resource_id IS NULL OR r.id = p_resource_id)
  ),
  days AS (
    SELECT d::date AS day
      FROM zone, generate_series(
             (p_from AT TIME ZONE zone.tz)::date::timestamp,
             (p_to   AT TIME ZONE zone.tz)::date::timestamp,
             interval '1 day'
           ) AS d
  ),
  -- Hours for one resource on one day. A resource with its own hours for that
  -- weekday uses only those; otherwise the whole business's hours apply.
  windows AS (
    SELECT u.id AS resource_id, d.day, h.open_time, h.close_time
      FROM days d
      CROSS JOIN usable u
      JOIN LATERAL (
        SELECT b.open_time, b.close_time
          FROM business_hours b
         WHERE b.resource_id = u.id
           AND b.weekday = extract(dow FROM d.day)::int
        UNION ALL
        SELECT b.open_time, b.close_time
          FROM business_hours b
         WHERE b.resource_id IS NULL
           AND b.weekday = extract(dow FROM d.day)::int
           AND NOT EXISTS (
             SELECT 1 FROM business_hours o
              WHERE o.resource_id = u.id AND o.weekday = b.weekday
           )
      ) h ON true
     WHERE NOT EXISTS (
       SELECT 1 FROM business_closures c
        WHERE d.day BETWEEN c.starts_on AND c.ends_on
          AND (c.resource_id IS NULL OR c.resource_id = u.id)
     )
  ),
  candidates AS (
    SELECT w.resource_id,
           gs AS starts_at,
           gs + make_interval(mins => svc.duration_minutes) AS ends_at
      FROM windows w, svc, zone,
      LATERAL generate_series(
        (w.day + w.open_time) AT TIME ZONE zone.tz,
        ((w.day + w.close_time) AT TIME ZONE zone.tz) - make_interval(mins => svc.duration_minutes),
        make_interval(mins => GREATEST(COALESCE(p_step_minutes, svc.duration_minutes), 5))
      ) AS gs
  )
  SELECT c.resource_id, c.starts_at, c.ends_at
    FROM candidates c, svc
   WHERE c.starts_at >= p_from
     AND c.ends_at <= p_to
     -- Nothing already booked may touch this slot once both sides' buffers are
     -- allowed for. The exclusion constraint only refuses raw overlaps; buffers
     -- are scheduling policy and live here and in book_appointment().
     AND NOT EXISTS (
       SELECT 1
         FROM appointments a
         JOIN services s2 ON s2.id = a.service_id
        WHERE a.resource_id = c.resource_id
          AND a.status NOT IN ('cancelled', 'no_show')
          AND tstzrange(
                c.starts_at - make_interval(mins => svc.buffer_before_minutes),
                c.ends_at   + make_interval(mins => svc.buffer_after_minutes)
              ) && tstzrange(
                a.starts_at - make_interval(mins => s2.buffer_before_minutes),
                a.ends_at   + make_interval(mins => s2.buffer_after_minutes)
              )
     )
     -- A service capped at so many a day stops being offered once it is full.
     AND (
       svc.max_per_day IS NULL
       OR (
         SELECT count(*)
           FROM appointments a2, zone
          WHERE a2.service_id = p_service_id
            AND a2.status NOT IN ('cancelled', 'no_show')
            AND (a2.starts_at AT TIME ZONE zone.tz)::date = (c.starts_at AT TIME ZONE zone.tz)::date
       ) < svc.max_per_day
     )
   ORDER BY c.starts_at, c.resource_id
$$;
COMMENT ON FUNCTION available_slots(bigint, bigint, timestamptz, timestamptz, integer) IS 'Bookable slots for a service between two instants: opening hours minus closures, existing appointments and buffers, in the business timezone. p_resource_id null means any resource that offers it.';

-- Booking, safely ----------------------------------------------------------------
-- The only sanctioned way to create an appointment, in the same spirit as
-- apply_stock_change() in 004.
--
-- pg_advisory_xact_lock serialises every booking for one resource: the second
-- of two simultaneous requests waits for the first to commit, then re-checks
-- and loses cleanly. Without it both could pass their overlap check before
-- either had written anything. The lock is held to the end of the transaction
-- and released automatically, including on rollback.
CREATE OR REPLACE FUNCTION book_appointment(
  p_service_id  bigint,
  p_resource_id bigint,
  p_starts_at   timestamptz,
  p_customer_id bigint DEFAULT NULL,
  p_status      text DEFAULT 'requested',
  p_source      text DEFAULT 'operator',
  p_notes       text DEFAULT NULL
)
RETURNS appointments
LANGUAGE plpgsql AS $$
DECLARE
  v_service     services;
  v_resource    resources;
  v_ends_at     timestamptz;
  v_clash       text;
  v_appointment appointments;
BEGIN
  SELECT * INTO v_service FROM services WHERE id = p_service_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That service does not exist.' USING ERRCODE = 'foreign_key_violation', HINT = 'docdesk';
  END IF;
  IF NOT v_service.is_active THEN
    RAISE EXCEPTION '% is not being offered at the moment.', v_service.name USING ERRCODE = 'check_violation', HINT = 'docdesk';
  END IF;

  SELECT * INTO v_resource FROM resources WHERE id = p_resource_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That is not one of the people or places that can be booked.' USING ERRCODE = 'foreign_key_violation', HINT = 'docdesk';
  END IF;
  IF NOT v_resource.is_active THEN
    RAISE EXCEPTION '% is not taking bookings at the moment.', v_resource.name USING ERRCODE = 'check_violation', HINT = 'docdesk';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM resource_services WHERE resource_id = p_resource_id AND service_id = p_service_id) THEN
    RAISE EXCEPTION '% does not do %.', v_resource.name, v_service.name USING ERRCODE = 'check_violation', HINT = 'docdesk';
  END IF;

  v_ends_at := p_starts_at + make_interval(mins => v_service.duration_minutes);

  -- Everything past this point is serialised per resource.
  PERFORM pg_advisory_xact_lock(hashtext('docdesk.resource'), p_resource_id::int);

  SELECT a.reference INTO v_clash
    FROM appointments a
    JOIN services s ON s.id = a.service_id
   WHERE a.resource_id = p_resource_id
     AND a.status NOT IN ('cancelled', 'no_show')
     AND tstzrange(
           p_starts_at - make_interval(mins => v_service.buffer_before_minutes),
           v_ends_at   + make_interval(mins => v_service.buffer_after_minutes)
         ) && tstzrange(
           a.starts_at - make_interval(mins => s.buffer_before_minutes),
           a.ends_at   + make_interval(mins => s.buffer_after_minutes)
         )
   ORDER BY a.starts_at
   LIMIT 1;

  IF v_clash IS NOT NULL THEN
    RAISE EXCEPTION '% is already booked then (%).', v_resource.name, v_clash
      USING ERRCODE = 'exclusion_violation', HINT = 'docdesk';
  END IF;

  INSERT INTO appointments (customer_id, service_id, resource_id, starts_at, ends_at, status, source, notes)
  VALUES (p_customer_id, p_service_id, p_resource_id, p_starts_at, v_ends_at, p_status, p_source, p_notes)
  RETURNING * INTO v_appointment;

  RETURN v_appointment;
END
$$;
COMMENT ON FUNCTION book_appointment(bigint, bigint, timestamptz, bigint, text, text, text) IS 'Creates an appointment, serialising on the resource so two simultaneous bookings cannot both win.';

-- Moves an appointment to a new time, re-checking the clash under the same lock.
CREATE OR REPLACE FUNCTION reschedule_appointment(
  p_appointment_id bigint,
  p_starts_at      timestamptz,
  p_resource_id    bigint DEFAULT NULL,
  p_reason         text DEFAULT NULL
)
RETURNS appointments
LANGUAGE plpgsql AS $$
DECLARE
  v_appointment appointments;
  v_service     services;
  v_resource_id bigint;
  v_ends_at     timestamptz;
  v_clash       text;
BEGIN
  SELECT * INTO v_appointment FROM appointments WHERE id = p_appointment_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That appointment does not exist.' USING ERRCODE = 'foreign_key_violation', HINT = 'docdesk';
  END IF;
  IF v_appointment.status IN ('cancelled', 'completed', 'no_show') THEN
    RAISE EXCEPTION '% is already %, so it cannot be moved. Book a new one.', v_appointment.reference, replace(v_appointment.status, '_', ' ')
      USING ERRCODE = 'check_violation', HINT = 'docdesk';
  END IF;

  SELECT * INTO v_service FROM services WHERE id = v_appointment.service_id;
  v_resource_id := COALESCE(p_resource_id, v_appointment.resource_id);
  v_ends_at := p_starts_at + make_interval(mins => v_service.duration_minutes);

  IF v_resource_id <> v_appointment.resource_id
     AND NOT EXISTS (SELECT 1 FROM resource_services WHERE resource_id = v_resource_id AND service_id = v_service.id) THEN
    RAISE EXCEPTION 'That person or place does not do %.', v_service.name USING ERRCODE = 'check_violation', HINT = 'docdesk';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext('docdesk.resource'), v_resource_id::int);

  SELECT a.reference INTO v_clash
    FROM appointments a
    JOIN services s ON s.id = a.service_id
   WHERE a.resource_id = v_resource_id
     AND a.id <> p_appointment_id
     AND a.status NOT IN ('cancelled', 'no_show')
     AND tstzrange(
           p_starts_at - make_interval(mins => v_service.buffer_before_minutes),
           v_ends_at   + make_interval(mins => v_service.buffer_after_minutes)
         ) && tstzrange(
           a.starts_at - make_interval(mins => s.buffer_before_minutes),
           a.ends_at   + make_interval(mins => s.buffer_after_minutes)
         )
   LIMIT 1;

  IF v_clash IS NOT NULL THEN
    RAISE EXCEPTION 'That time is already taken (%).', v_clash USING ERRCODE = 'exclusion_violation', HINT = 'docdesk';
  END IF;

  UPDATE appointments
     SET starts_at = p_starts_at, ends_at = v_ends_at, resource_id = v_resource_id
   WHERE id = p_appointment_id
  RETURNING * INTO v_appointment;

  INSERT INTO appointment_events (appointment_id, status, reason, actor, created_at)
  VALUES (p_appointment_id, v_appointment.status, COALESCE(p_reason, 'Moved to another time'), app_actor(), app_clock());

  RETURN v_appointment;
END
$$;
COMMENT ON FUNCTION reschedule_appointment(bigint, timestamptz, bigint, text) IS 'Moves an appointment, re-checking for a clash under the same per-resource lock a new booking takes.';

-- Records a change of state. The only way appointments.status ever moves.
CREATE OR REPLACE FUNCTION set_appointment_status(
  p_appointment_id bigint,
  p_status         text,
  p_reason         text DEFAULT NULL
)
RETURNS appointments
LANGUAGE plpgsql AS $$
DECLARE
  v_appointment appointments;
BEGIN
  SELECT * INTO v_appointment FROM appointments WHERE id = p_appointment_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That appointment does not exist.' USING ERRCODE = 'foreign_key_violation', HINT = 'docdesk';
  END IF;

  INSERT INTO appointment_events (appointment_id, status, reason, actor, created_at)
  VALUES (p_appointment_id, p_status, p_reason, app_actor(), app_clock());

  SELECT * INTO v_appointment FROM appointments WHERE id = p_appointment_id;
  RETURN v_appointment;
END
$$;
COMMENT ON FUNCTION set_appointment_status(bigint, text, text) IS 'Adds an event, which is what moves an appointment between requested, confirmed, arrived, completed, no_show and cancelled.';

-- What the front desk reads ------------------------------------------------------
CREATE OR REPLACE VIEW v_appointments AS
SELECT
  a.id,
  a.reference,
  a.starts_at,
  a.ends_at,
  a.status,
  a.source,
  a.notes,
  a.customer_id,
  c.name  AS customer_name,
  c.phone AS customer_phone,
  a.service_id,
  s.name  AS service_name,
  s.duration_minutes,
  s.price,
  s.colour,
  a.resource_id,
  r.name  AS resource_name,
  r.kind  AS resource_kind,
  (a.starts_at AT TIME ZONE business_timezone())::date AS day,
  a.created_at,
  a.updated_at,
  a.row_version
FROM appointments a
JOIN services s  ON s.id = a.service_id
JOIN resources r ON r.id = a.resource_id
LEFT JOIN customers c ON c.id = a.customer_id;
COMMENT ON VIEW v_appointments IS 'Each appointment with its customer, service and resource, and the calendar day it falls on in the business timezone.';

-- Reports whether the hard overlap guarantee is in place, so the Health tab can
-- say so rather than everyone assuming it.
CREATE OR REPLACE FUNCTION scheduling_capabilities() RETURNS jsonb
LANGUAGE sql STABLE AS $$
  SELECT jsonb_build_object(
    'exclusion_constraint', EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_no_overlap'),
    'btree_gist', EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'btree_gist'),
    'advisory_lock', true
  )
$$;
COMMENT ON FUNCTION scheduling_capabilities() IS 'Which overlap protections this database actually has. The advisory lock is always there; the exclusion constraint needs btree_gist.';
