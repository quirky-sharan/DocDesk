-- Status is derived, never assigned ---------------------------------------------
-- The same shape as payments -> sales.payment_status in 004: the child rows are
-- the truth, a trigger keeps the parent column in step, and the parent column is
-- read-only to everybody else.
CREATE OR REPLACE FUNCTION appointment_events_sync() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_appointment_id bigint;
  v_status         text;
BEGIN
  IF app_restoring() THEN
    RETURN NULL;
  END IF;
  v_appointment_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.appointment_id ELSE NEW.appointment_id END;

  SELECT e.status INTO v_status
    FROM appointment_events e
   WHERE e.appointment_id = v_appointment_id
   ORDER BY e.created_at DESC, e.id DESC
   LIMIT 1;

  -- No events left (the last one was deleted) means nothing has happened to it
  -- yet, which is what 'requested' means.
  PERFORM set_config('docdesk.appointment_sync', 'on', true);
  UPDATE appointments SET status = COALESCE(v_status, 'requested')
   WHERE id = v_appointment_id AND status IS DISTINCT FROM COALESCE(v_status, 'requested');
  PERFORM set_config('docdesk.appointment_sync', 'off', true);
  RETURN NULL;
END
$$;

CREATE OR REPLACE TRIGGER appointment_events_sync AFTER INSERT OR UPDATE OR DELETE ON appointment_events
  FOR EACH ROW EXECUTE FUNCTION appointment_events_sync();

-- Records how an appointment started, so its history is complete from the first
-- row rather than starting at its first change.
CREATE OR REPLACE FUNCTION appointments_open_history() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF app_restoring() THEN
    RETURN NULL;
  END IF;
  INSERT INTO appointment_events (appointment_id, status, reason, actor, created_at)
  VALUES (NEW.id, NEW.status, 'Booked', app_actor(), app_clock());
  RETURN NULL;
END
$$;

CREATE OR REPLACE TRIGGER appointments_open_history AFTER INSERT ON appointments
  FOR EACH ROW EXECUTE FUNCTION appointments_open_history();

CREATE OR REPLACE FUNCTION appointments_guard_status() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status
     AND COALESCE(app_setting('docdesk.appointment_sync'), 'off') <> 'on'
     AND NOT app_restoring() THEN
    RAISE EXCEPTION 'An appointment''s status comes from its history. Record the change in appointment_events instead of setting % directly.', NEW.status
      USING ERRCODE = 'check_violation', HINT = 'docdesk';
  END IF;
  RETURN NEW;
END
$$;

CREATE OR REPLACE TRIGGER appointments_guard_status BEFORE UPDATE OF status ON appointments
  FOR EACH ROW EXECUTE FUNCTION appointments_guard_status();

