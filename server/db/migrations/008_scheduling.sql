-- 008 Scheduling: services, resources, opening hours and appointments.
--
--   services  *-* resources        (resource_services: who can do what)
--   resources 1-* business_hours   (null resource_id = the whole business)
--   resources 1-* appointments 1-* appointment_events
--
-- Two rules are worth stating before the tables:
--
-- 1. An appointment's status is NEVER set directly. It is derived from its
--    events by trigger, exactly the way a sale's payment_status is derived from
--    its payments (004). Writing appointments.status by hand raises.
--
-- 2. Double-booking is prevented by the database, not by the application. Two
--    requests that arrive at the same instant cannot both win, because
--    book_appointment() takes a lock on the resource and re-checks inside it,
--    and (where the extension exists) an exclusion constraint refuses the
--    overlap outright even for a write that bypasses the function entirely.
--
-- Money is numeric(14,2) here to match products.sale_price. The build spec for
-- this phase asked for integer cents, but the rest of this schema is numeric
-- and two money representations in one database is a bug waiting to happen -
-- a report joining services and products would need two different conversions.
-- Amounts are still computed in integer cents in JS (lib/money.js) so the
-- rounding matches; only the storage type differs from the spec.

-- btree_gist lets a GiST index cover a plain bigint next to a range, which is
-- what the no-overlap constraint below needs. Wrapped like pg_trgm in 001: if
-- it is unavailable the constraint is skipped and book_appointment()'s lock is
-- the only guard. Never let an optional extension be load-bearing.
DO $$
BEGIN
  CREATE EXTENSION IF NOT EXISTS btree_gist;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'btree_gist is unavailable (%). Overlap protection falls back to the advisory lock in book_appointment().', SQLERRM;
END
$$;

