-- 014 Accounts: who may use DocDesk, and the sessions they are signed in with.
--
-- Until now the browser signed in with Firebase and the API believed anyone who
-- could reach it. From here the API keeps its own list of people and checks
-- every request against it.
--
-- `users` was reserved in 002 for a username-and-password sign-in that was never
-- built, and nothing has ever written to it. Sign-in is Firebase Authentication,
-- so DocDesk never sees a password and has nowhere to keep one: the table is
-- rebuilt around the Firebase account id instead.

DROP TABLE IF EXISTS users;

CREATE TABLE users (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firebase_uid text NOT NULL,
  email        text,
  display_name text,
  photo_url    text,
  role         text NOT NULL DEFAULT 'staff',
  status       text NOT NULL DEFAULT 'pending',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz,
  CONSTRAINT users_firebase_uid_key UNIQUE (firebase_uid),
  CONSTRAINT users_role_check CHECK (role IN ('owner', 'manager', 'staff')),
  CONSTRAINT users_status_check CHECK (status IN ('active', 'pending', 'disabled'))
);
COMMENT ON TABLE users IS 'Everyone who has signed in. The first becomes the owner; the rest wait as pending until an owner lets them in.';
COMMENT ON COLUMN users.firebase_uid IS 'The account id from Firebase Authentication. Passwords live there, never here.';
COMMENT ON COLUMN users.status IS 'pending: signed in but not let in yet. disabled: turned away, kept so the same account cannot simply sign up again.';

-- A session is the cookie's other half. Only a SHA-256 of the cookie is stored,
-- so reading this table (a backup, the SQL console) does not hand anyone a
-- working session.
CREATE TABLE IF NOT EXISTS sessions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash   text NOT NULL,
  user_id      bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL,
  CONSTRAINT sessions_token_hash_key UNIQUE (token_hash),
  CONSTRAINT sessions_token_hash_format CHECK (token_hash ~ '^[0-9a-f]{64}$')
);
CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON sessions (user_id);
CREATE INDEX IF NOT EXISTS sessions_expires_at_idx ON sessions (expires_at);
COMMENT ON TABLE sessions IS 'Signed-in browsers. Deleting a row signs that browser out on its next request.';
COMMENT ON COLUMN sessions.token_hash IS 'SHA-256 of the session cookie. The cookie itself is never stored.';

-- Somebody must always be able to let people in and out. Checked once per
-- statement, after it, so swapping two roles in one UPDATE is allowed but
-- ending up with nobody in charge is not - whatever made the change.
CREATE OR REPLACE FUNCTION users_keep_an_owner() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM users)
     AND NOT EXISTS (SELECT 1 FROM users WHERE role = 'owner' AND status = 'active') THEN
    RAISE EXCEPTION 'There has to be at least one owner. Make someone else an owner first.'
      USING ERRCODE = 'check_violation', HINT = 'docdesk';
  END IF;
  RETURN NULL;
END
$$;
COMMENT ON FUNCTION users_keep_an_owner() IS 'Refuses any change that would leave DocDesk with no active owner.';

CREATE OR REPLACE TRIGGER users_keep_an_owner
  AFTER UPDATE OR DELETE ON users
  FOR EACH STATEMENT EXECUTE FUNCTION users_keep_an_owner();

CREATE OR REPLACE FUNCTION users_touch() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END
$$;

CREATE OR REPLACE TRIGGER users_touch
  BEFORE UPDATE OF email, display_name, photo_url, role, status ON users
  FOR EACH ROW EXECUTE FUNCTION users_touch();

-- The audit trail records which part of DocDesk made a change (the app, the
-- receptionist, the SQL console). With more than one person signed in it also
-- needs to say who.
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS user_label text;
COMMENT ON COLUMN audit_log.user_label IS 'The signed-in person the change was made by or on behalf of, where there was one.';

CREATE OR REPLACE FUNCTION audit_row() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_old     jsonb;
  v_new     jsonb;
  v_changed text[];
BEGIN
  IF app_restoring() OR app_setting('docdesk.skip_audit') = 'on' THEN
    RETURN NULL;
  END IF;

  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    v_old := to_jsonb(OLD);
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    v_new := to_jsonb(NEW);
  END IF;

  IF TG_OP = 'UPDATE' THEN
    SELECT array_agg(n.key ORDER BY n.key) INTO v_changed
      FROM jsonb_each(v_new) AS n
     WHERE n.key NOT IN ('updated_at', 'row_version')
       AND n.value IS DISTINCT FROM (v_old -> n.key);

    IF v_changed IS NULL THEN
      RETURN NULL;
    END IF;
    -- Stock moved by the ledger is already recorded, with its reason, in stock_movements.
    IF TG_TABLE_NAME = 'products' AND v_changed = ARRAY['stock_quantity'] AND app_setting('docdesk.ledger') = 'on' THEN
      RETURN NULL;
    END IF;
    -- Payment status follows the payments table, which is audited itself.
    IF TG_TABLE_NAME = 'sales' AND app_setting('docdesk.payment_sync') = 'on'
       AND v_changed <@ ARRAY['amount_paid', 'payment_status', 'payment_method'] THEN
      RETURN NULL;
    END IF;
  END IF;

  INSERT INTO audit_log (table_name, record_id, record_key, action, actor, user_label, changed_fields, old_data, new_data, created_at)
  VALUES (
    TG_TABLE_NAME,
    CASE WHEN COALESCE(v_new, v_old) ? 'id' THEN (COALESCE(v_new, v_old) ->> 'id')::bigint END,
    CASE WHEN COALESCE(v_new, v_old) ? 'key' THEN COALESCE(v_new, v_old) ->> 'key' END,
    TG_OP,
    app_actor(),
    app_setting('docdesk.user'),
    v_changed,
    v_old,
    v_new,
    app_clock()
  );
  RETURN NULL;
END
$$;

-- Who was let in, promoted or turned away is exactly the kind of change the
-- trail exists for. Sessions are deliberately not audited: they change on every
-- sign-in and hold nothing a person decided.
CREATE OR REPLACE TRIGGER users_audit AFTER INSERT OR UPDATE OR DELETE ON users FOR EACH ROW EXECUTE FUNCTION audit_row();
